import os
from google import genai
from dotenv import load_dotenv

# Завантажуємо змінні з .env
load_dotenv()

# Створюємо клієнт
client = genai.Client(api_key=os.getenv("GEMINI_API_KEY"))

def get_pc_recommendation(user_query: str):
    """
    Отримує запит користувача та просить ШІ зібрати ідеальний ПК з УСІХ існуючих у світі деталей.
    """
    prompt = f"""
    Ти — професійний консультант з підбору комп'ютерної техніки.
    Твоє завдання: допомогти користувачу зібрати ідеальний ПК під його потреби та бюджет.
    
    Запит користувача: "{user_query}"

    Підбери найкращі реальні комплектуючі (процесор, відеокарта, материнська плата, ОЗП, накопичувач, блок живлення, корпус), які зараз існують на ринку.
    Напиши приблизні актуальні ціни в гривнях (UAH) для кожної деталі та загальну суму.
    Відповідь має бути красиво відформатована, з коротким поясненням, чому обрано саме цю зв'язку (наприклад, чому процесор добре розкриває відеокарту).
    Спілкуйся українською мовою, будь ввічливим та експертним.
    """

    # Звертаємося до моделі
    response = client.models.generate_content(
        model='gemini-2.5-flash',
        contents=prompt,
    )
    return response.text